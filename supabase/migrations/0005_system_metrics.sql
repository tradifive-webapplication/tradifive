-- Create system_metrics table
CREATE TABLE IF NOT EXISTS public.system_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpu_usage NUMERIC NOT NULL,
    memory_usage NUMERIC NOT NULL,
    network_in NUMERIC NOT NULL,
    network_out NUMERIC NOT NULL,
    db_latency NUMERIC NOT NULL,
    active_connections INTEGER NOT NULL,
    requests_per_min INTEGER NOT NULL,
    error_rate NUMERIC NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Keep only the last 100 rows to prevent table bloat
-- Create a function and trigger to auto-delete old rows
CREATE OR REPLACE FUNCTION public.trim_system_metrics()
RETURNS TRIGGER AS $$
BEGIN
  DELETE FROM public.system_metrics
  WHERE id NOT IN (
    SELECT id FROM public.system_metrics ORDER BY created_at DESC LIMIT 100
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_trim_system_metrics
AFTER INSERT ON public.system_metrics
FOR EACH STATEMENT
EXECUTE FUNCTION public.trim_system_metrics();

-- Enable realtime for system_metrics
ALTER PUBLICATION supabase_realtime ADD TABLE public.system_metrics;
